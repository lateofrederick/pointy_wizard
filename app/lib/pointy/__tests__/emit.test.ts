import { describe, expect, it } from 'vitest';
import { emit, emitEvent, emitExpr } from '../emit';
import type { Expr } from '../../../types/pointy';
import {
  screen03,
  screen03Expected,
  screen13,
  screen13Expected,
  screen16,
  screen16Expected,
  screen17,
  screen17Expected,
} from './fixtures';

describe('emit — against the prototype output panels', () => {
  it('screen 03: namespaces, meta event, group with attrs, retry, branch, CFG reuse', () => {
    expect(emit(screen03)).toBe(screen03Expected);
  });

  it('screen 13: explicit @mode and $variables in place of literals', () => {
    expect(emit(screen13)).toBe(screen13Expected);
  });

  it('screen 16: concurrency group and a remote executor with a map attribute', () => {
    expect(emit(screen16)).toBe(screen16Expected);
  });

  it('screen 17: a || pair feeding a meta event', () => {
    expect(emit(screen17)).toBe(screen17Expected);
  });
});

describe('emit — document rules', () => {
  it('omits @mode when it is unset, because unset means CFG', () => {
    expect(emit(screen03)).not.toContain('@mode');
  });

  it('emits @mode when it is set explicitly', () => {
    expect(emit(screen13)).toContain('@mode: "CFG"');
  });

  it('never writes the implicit local:: namespace', () => {
    expect(emit(screen03)).not.toContain('local::');
  });

  it('handles an empty document without inventing a chain', () => {
    const out = emit({
      name: 'untitled',
      directives: {},
      variables: [],
      sources: [],
      chain: null,
      definitions: {},
      layout: {},
    });
    expect(out).toBe('# untitled.pointy — generated by Pointy Wizard\n\n# no events yet\n');
  });
});

describe('emitEvent', () => {
  const base = { id: 'x', name: 'Thing', namespace: 'local' as const, attributes: [] };

  it('writes a bare retry as *', () => {
    expect(emitEvent({ ...base, retry: 'default' })).toBe('Thing *');
  });

  it('writes a numeric retry as * n', () => {
    expect(emitEvent({ ...base, retry: 3 })).toBe('Thing * 3');
  });

  it('puts meta-level attributes before template-level ones in one bracket', () => {
    expect(
      emitEvent({
        ...base,
        name: 'Parse',
        attributes: [{ name: 'executor', value: { kind: 'literal', value: 'process' } }],
        meta: {
          mode: 'MAP',
          template: 'Parse',
          metaAttributes: [{ name: 'batch_size', value: { kind: 'literal', value: 50 } }],
        },
      }),
    ).toBe('MAP<Parse>[batch_size=50, executor="process"]');
  });

  it('prefixes a non-local namespace', () => {
    expect(emitEvent({ ...base, namespace: 'pypi' })).toBe('pypi::Thing');
  });
});

describe('emitExpr — the whole expression grammar', () => {
  const cases: [string, Expr][] = [
    ['42', { kind: 'literal', value: 42 }],
    ['true', { kind: 'literal', value: true }],
    ['null', { kind: 'literal', value: null }],
    ['"hi"', { kind: 'literal', value: 'hi' }],
    ['$batch_size', { kind: 'ref', name: 'batch_size' }],
    ['$env.TIMEOUT', { kind: 'env', name: 'TIMEOUT' }],
    [
      '$env.A ?? $env.B ?? "localhost"',
      {
        kind: 'coalesce',
        operands: [
          { kind: 'env', name: 'A' },
          { kind: 'env', name: 'B' },
          { kind: 'literal', value: 'localhost' },
        ],
      },
    ],
    [
      '$zone == "eu" ? "eu-west-1" : "us-east-1"',
      {
        kind: 'ternary',
        left: { kind: 'ref', name: 'zone' },
        op: '==',
        right: { kind: 'literal', value: 'eu' },
        then: { kind: 'literal', value: 'eu-west-1' },
        otherwise: { kind: 'literal', value: 'us-east-1' },
      },
    ],
    ['[1, 2]', { kind: 'list', items: [{ kind: 'literal', value: 1 }, { kind: 'literal', value: 2 }] }],
  ];

  for (const [expected, expr] of cases) {
    it(`renders ${expected}`, () => expect(emitExpr(expr)).toBe(expected));
  }

  it('escapes quotes inside strings', () => {
    expect(emitExpr({ kind: 'literal', value: 'say "hi"' })).toBe('"say \\"hi\\""');
  });
});

import type { Chain, EventRef, PointyDocument } from '../../../types/pointy';

/**
 * Documents reconstructed from the Figma prototype's output panels.
 *
 * These are the emitter's spec: the panels were written and checked by hand
 * during design, so if emit() and a panel disagree, one of them is a bug and
 * the disagreement is worth resolving rather than papering over.
 */

const ev = (
  id: string,
  name: string,
  extra: Partial<Omit<EventRef, 'id' | 'name'>> = {},
): EventRef => ({
  id,
  name,
  namespace: 'local',
  attributes: [],
  definitionId: `${id}.py`,
  ...extra,
});

const e = (ref: EventRef): Chain => ({ kind: 'event', ref });
const str = (value: string) => ({ kind: 'literal' as const, value });
const num = (value: number) => ({ kind: 'literal' as const, value });

